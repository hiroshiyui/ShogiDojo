"""Dataset for loading SFEN training data with evaluations.

=== Training Data Format ===

Training data for NNUE is typically generated by a Shogi engine (like
YaneuraOu or Apery) performing self-play or analyzing existing game records.
For each position, the engine records:

  1. The position (in SFEN format)
  2. The engine's evaluation score (in centipawns, from side-to-move's view)
  3. The game result (did the side-to-move ultimately win, lose, or draw?)

The NNUE is trained to predict BOTH the engine score AND the game result.
Using both signals helps the network learn:
  - From scores: fine-grained positional understanding (tactical accuracy)
  - From results: long-term strategic patterns (which positions actually win)

=== Data File Format ===

Each line in the training file represents one position:

    sfen <board> <side> <hand> <move#> <score> <result>

Example:
    sfen lnsgkgsnl/1r5b1/ppppppppp/9/9/9/PPPPPPPPP/1B5R1/LNSGKGSNL b - 1\t100\t1.0

Fields:
    - board:  SFEN board string (pieces on the 9x9 grid)
    - side:   'b' (Black/Sente to move) or 'w' (White/Gote to move)
    - hand:   pieces in hand ('-' if none, e.g. 'S2P' = 1 Silver + 2 Pawns)
    - move#:  full move number
    - score:  centipawn evaluation (positive = good for side-to-move)
    - result: game outcome for side-to-move: 1.0 = win, 0.5 = draw, 0.0 = loss
"""

from __future__ import annotations

import os
from typing import Iterator

import numpy as np
import torch
from torch.utils.data import Dataset, IterableDataset

from .features import sfen_to_features


class SfenDataset(IterableDataset):
    """Streaming dataset that reads SFEN training data line by line.

    Uses IterableDataset (instead of map-style Dataset) because training
    files can be very large (tens of GB). Streaming avoids loading everything
    into memory at once — we read one line at a time.

    When using multiple DataLoader workers, each worker processes a different
    subset of lines (round-robin assignment) to avoid duplicating work.
    """

    def __init__(self, path: str, score_scaling: float = 600.0):
        """
        Args:
            path: Path to the SFEN training data file.
            score_scaling: Divide raw centipawn scores by this value before
                           training. This normalizes scores to a reasonable
                           range for the sigmoid function.
                           Default 600 means a 600cp advantage maps to ~0.73
                           after sigmoid, which roughly corresponds to a 73%
                           win probability.
        """
        self.path = path
        self.score_scaling = score_scaling

    def __iter__(self) -> Iterator[dict[str, torch.Tensor]]:
        # When using multiple DataLoader workers (num_workers > 0), PyTorch
        # creates separate processes. Each worker gets a worker_info object
        # telling it which worker it is. We use this to split work evenly:
        # worker 0 handles lines 0, 4, 8, ...; worker 1 handles lines 1, 5, 9, ...
        worker_info = torch.utils.data.get_worker_info()

        with open(self.path, 'r') as f:
            for line_no, line in enumerate(f):
                # Round-robin: skip lines that belong to other workers
                if worker_info is not None:
                    if line_no % worker_info.num_workers != worker_info.id:
                        continue

                line = line.strip()
                if not line:
                    continue

                sample = self._parse_line(line)
                if sample is not None:
                    yield sample

    def _parse_line(self, line: str) -> dict[str, torch.Tensor] | None:
        """Parse a single training data line into a training sample.

        Returns None if the line is malformed (silently skips bad data).
        """
        try:
            # Strip the "sfen " prefix if present
            if line.startswith('sfen '):
                line = line[5:]

            # Split on whitespace. The SFEN position has 4 fields,
            # followed by the score and result.
            # Example after stripping prefix:
            #   "lnsgkgsnl/... b - 1 100 1.0"
            #   parts[0]="lnsgkgsnl/..."  parts[1]="b"  parts[2]="-"
            #   parts[3]="1"  parts[4]="100"  parts[5]="1.0"
            parts = line.split()
            if len(parts) < 6:
                return None

            sfen_str = ' '.join(parts[:4])  # Rejoin the 4 SFEN fields
            score = float(parts[4])         # Centipawn evaluation
            result = float(parts[5])        # Game result (0.0, 0.5, or 1.0)

            # Convert the SFEN position to sparse feature indices
            stm_indices, nstm_indices, _ = sfen_to_features(sfen_str)

            return {
                'stm_indices': torch.tensor(stm_indices, dtype=torch.long),
                'nstm_indices': torch.tensor(nstm_indices, dtype=torch.long),
                # Scale the score to a range suitable for sigmoid.
                # score_scaling=600 means a ±600cp range maps to roughly ±1.
                'score': torch.tensor(score / self.score_scaling, dtype=torch.float32),
                'result': torch.tensor(result, dtype=torch.float32),
            }
        except Exception:
            # Skip any line that can't be parsed (corrupted data, etc.)
            return None


def collate_fn(batch: list[dict[str, torch.Tensor]]) -> dict[str, torch.Tensor]:
    """Combine individual samples into a single batched tensor.

    === Why do we need a custom collate function? ===

    Each position has a different number of pieces on the board, so the
    sparse index tensors have different lengths. PyTorch's default collate
    can't stack tensors of different sizes. We solve this by padding all
    index tensors in a batch to the same length, using -1 as a padding value.

    The model's FeatureTransformer knows to ignore -1 indices (see model.py).

    Example:
        Sample 1: stm_indices = [10, 25, 300]        (3 pieces)
        Sample 2: stm_indices = [10, 25, 300, 1500]  (4 pieces)

        After padding:
        stm_indices = [[10, 25, 300,  -1],   ← padded with -1
                       [10, 25, 300, 1500]]

    Args:
        batch: List of sample dicts from SfenDataset.__iter__().

    Returns:
        A batched dict with:
        - 'stm_indices':  (batch_size, max_active) padded with -1
        - 'nstm_indices': (batch_size, max_active) padded with -1
        - 'score':        (batch_size,) float tensor
        - 'result':       (batch_size,) float tensor
    """
    # Find the maximum number of active features in this batch
    max_stm = max(b['stm_indices'].size(0) for b in batch)
    max_nstm = max(b['nstm_indices'].size(0) for b in batch)

    batch_size = len(batch)

    # Pre-allocate padded tensors filled with -1 (the "invalid index" sentinel)
    stm_padded = torch.full((batch_size, max_stm), -1, dtype=torch.long)
    nstm_padded = torch.full((batch_size, max_nstm), -1, dtype=torch.long)
    scores = torch.zeros(batch_size, dtype=torch.float32)
    results = torch.zeros(batch_size, dtype=torch.float32)

    # Copy each sample's data into the padded tensors
    for i, b in enumerate(batch):
        s_len = b['stm_indices'].size(0)
        n_len = b['nstm_indices'].size(0)
        stm_padded[i, :s_len] = b['stm_indices']    # Valid indices fill the front
        nstm_padded[i, :n_len] = b['nstm_indices']  # Remaining slots stay as -1
        scores[i] = b['score']
        results[i] = b['result']

    return {
        'stm_indices': stm_padded,
        'nstm_indices': nstm_padded,
        'score': scores,
        'result': results,
    }
